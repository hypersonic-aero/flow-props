runner = CliRunner()


def _write_solution(folder: Path, dataset) -> None:
    """Write a dataset as solution.h5 (read back through cfd-io, like a real case)."""
    write_file(folder / "solution.h5", dataset, dtype="f8")


def _write_config(folder: Path, name: str, text: str) -> Path:
    """Write <name>.toml with the solution file and the given tables."""
    path = folder / f"{name}.toml"
    path.write_text(f'fname = "solution.h5"\n{text}', encoding="utf-8")
    return path


