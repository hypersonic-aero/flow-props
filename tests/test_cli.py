def test_shock_run_writes_curve_and_report_and_compares_with_the_shock_line(tmp_path, monkeypatch):
    dataset, j_true = shock_solution()
    _write_solution(tmp_path, dataset)
    _write_config(tmp_path, "shock", "[shock]\nshock_line_j = 55\n")
    monkeypatch.chdir(tmp_path)

    result = runner.invoke(app, ["shock", "run"])

    # report: every line, the offset range against j = 55
    assert result.exit_code == 0, result.output
    assert f"Shock on {j_true.size} of {j_true.size} grid lines" in result.output
    assert "offset from shock line j = 55 (from [shock] shock_line_j)" in result.output

    # curve: one point per line
    curve = np.loadtxt("shock_cfd.csv", delimiter=",", skiprows=1)
    assert curve.shape == (j_true.size, 2)

    # report file: x, y are the shock points (raw), the offset column holds j_shock - 55
    lines = Path("shock_report.dat").read_text().splitlines()
    variables = [name.strip('" ') for name in lines[1].split("=")[1].split(",")]
    rows = np.loadtxt(lines[3:], ndmin=2)
    assert variables[:2] == ["x", "y"]
    np.testing.assert_allclose(rows[:, 0], dataset.grid.x[:, 0, 0], atol=1e-12)
    np.testing.assert_allclose(rows[:, variables.index("x_wall")], dataset.grid.x[:, 0, 0])
    offsets = rows[:, variables.index("offset_cells")]
    np.testing.assert_allclose(offsets, j_true - 55.0, atol=0.15)


def test_shock_run_smoothing_option(tmp_path):
    """Smoothed by default (and reported); smoothing_length = 0 writes the points as found."""
    dataset, _ = shock_solution()
    _write_solution(tmp_path, dataset)

    # default: smoothed, with the raw and smoothed points in the report
    path = _write_config(tmp_path, "shock", "")
    result = runner.invoke(app, ["shock", "run", "-c", str(path)])
    assert result.exit_code == 0, result.output
    assert "smoothed over 0.5 shock distances: points moved by up to" in result.output
    assert '"smoothing_cells"' in (tmp_path / "shock_report.dat").read_text()

    # off
    path = _write_config(tmp_path, "shock", "[shock]\nsmoothing_length = 0\n")
    result = runner.invoke(app, ["shock", "run", "-c", str(path)])
    assert result.exit_code == 0, result.output
    assert "curve written as found" in result.output

    # a negative length is a config error
    path = _write_config(tmp_path, "shock", "[shock]\nsmoothing_length = -1.0\n")
    result = runner.invoke(app, ["shock", "run", "-c", str(path)])
    assert result.exit_code == 1
    assert "shock.smoothing_length" in result.output


@pytest.mark.parametrize("method", ["walk", "indicator", "hybrid"])
def test_shock_run_names_its_method(method, tmp_path):
    """The summary says how the jump was found; hybrid reports which detector found what."""
    dataset, j_true = shock_solution()
    _write_solution(tmp_path, dataset)
    path = _write_config(tmp_path, "shock", f'[shock]\nmethod = "{method}"\n')

    result = runner.invoke(app, ["shock", "run", "-c", str(path)])

    assert result.exit_code == 0, result.output
    assert f"Shock on {j_true.size} of {j_true.size} grid lines" in result.output
    assert f"method {method} (" in result.output
    if method == "hybrid":
        assert "found by the walk on" in result.output

    # check: detected_by in every report, holding the method's detector
    lines = (tmp_path / "shock_report.dat").read_text().splitlines()
    variables = [name.strip('" ') for name in lines[1].split("=")[1].split(",")]
    rows = np.loadtxt(lines[3:], ndmin=2)
    codes = set(rows[:, variables.index("detected_by")].tolist())
    expected = {"walk": {1.0}, "indicator": {2.0}, "hybrid": {1.0, 2.0, 3.0}}
    assert codes <= expected[method]


def _report_variables(folder: Path) -> list[str]:
    """Column names of a shock report, in order."""
    lines = (folder / "shock_report.dat").read_text().splitlines()
    variables = [name.strip('" ') for name in lines[1].split("=")[1].split(",")]
    return variables


def test_shock_report_columns_keep_their_places_whatever_the_options(tmp_path):
    """Same columns in the same order for every method and smoothing; offset_cells last."""
    dataset, _ = shock_solution()
    _write_solution(tmp_path, dataset)

    # run with different options
    tables = {
        "default": "",
        "walk_raw": '[shock]\nmethod = "walk"\nsmoothing_length = 0\n',
        "indicator": '[shock]\nmethod = "indicator"\n',
        "shock_line": "[shock]\nshock_line_j = 55\n",
    }
    variables = {}
    for label, table in tables.items():
        path = _write_config(tmp_path, "shock", table)
        result = runner.invoke(app, ["shock", "run", "-c", str(path)])
        assert result.exit_code == 0, result.output
        variables[label] = _report_variables(tmp_path)

    # check: one fixed layout, the offset from the shock line appended when there is one
    fixed = [
        "x", "y", "x_wall", "y_wall", "station", "j_shock", "j_foot", "distance",
        "thickness_cells", "detected_by", "x_smooth", "y_smooth", "j_smooth",
        "smoothing_cells",
    ]  # fmt: skip
    assert variables["default"] == fixed
    assert variables["walk_raw"] == fixed
    assert variables["indicator"] == fixed
    assert variables["shock_line"] == fixed + ["offset_cells"]


