def test_run_bl_writes_extracted_profiles(tmp_path, monkeypatch):
    """The CLI preserves profiles extracted from a structured HDF5 dataset."""
    x = np.broadcast_to(np.arange(3)[:, None, None], (3, 4, 1)).copy().astype(float)
    y = np.broadcast_to(np.arange(4)[None, :, None], (3, 4, 1)).copy().astype(float)
    grid = StructuredGrid(x=x, y=y, z=np.zeros_like(x))
    uvel = np.broadcast_to(np.linspace(0, 1, 4)[None, :, None], x.shape).copy()
    flow = {
        "uvel": Field(data=uvel, association="node"),
        "vvel": Field(data=np.zeros_like(x), association="node"),
        "dens": Field(data=np.ones_like(x), association="node"),
        "temp": Field(data=np.full_like(x, 300.0), association="node"),
    }
    dataset = Dataset(grid=grid, flow=flow, attrs={})
    monkeypatch.setattr("flow_props.pipeline._load_dataset", lambda fname, gname: dataset)
    config_path = tmp_path / "bl.toml"
    config_path.write_text(
        'fname = "base_flow.hdf5"\n[stations]\nlist = [1]\n'
        '[bl]\noutput = "properties.dat"\nprofiles_output = "profiles.dat"\n',
        encoding="utf-8",
    )

    result = runner.invoke(app, ["run", "--bl", "-c", str(config_path)])

    assert result.exit_code == 0, result.output
    assert (tmp_path / "properties.dat").is_file()
    profiles_text = (tmp_path / "profiles.dat").read_text(encoding="utf-8")
    assert 'ZONE T="x_1.0000_m_k_00001", I=4' in profiles_text
    assert '"u_tangent"' in profiles_text


def test_gas_metadata_prefers_overrides_then_hdf5_then_json(tmp_path):
    """Unit-tagged HDF5 attributes and flow-conditions JSON supply gas values."""
    input_path = tmp_path / "base_flow.hdf5"
    (tmp_path / "flow_conditions.json").write_text(
        '{"gamma": [1.3, "-"], "r_gas": [300.0, "J/(kg*K)"]}',
        encoding="utf-8",
    )

    gamma, gas_constant = _resolve_gas_properties(
        GasConfig(), {"gamma": "[1.4, '-']"}, input_path, required=True
    )
    assert (gamma, gas_constant) == (1.4, 300.0)

    gamma, gas_constant = _resolve_gas_properties(
        GasConfig(gas_constant=287.05), {}, input_path, required=True
    )
    assert (gamma, gas_constant) == (1.3, 287.05)


