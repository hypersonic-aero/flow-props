from typer.testing import CliRunner

from flow_props.cli.app import app
from flow_props.pipeline import _resolve_gas_properties
from flow_props.schema import GasConfig

runner = CliRunner()


def test_version_short_flag():
    result = runner.invoke(app, ["-V"])
    assert result.exit_code == 0
    assert "flow-props" in result.output


def test_no_args_shows_help():
    result = runner.invoke(app, [])
    # no_args_is_help exits with code 0 and prints usage
    assert "Usage" in result.output
    assert "init" in result.output
    assert "run" in result.output
    assert "examples" in result.output


def test_init_writes_full_config(tmp_path, monkeypatch):
    monkeypatch.chdir(tmp_path)
    result = runner.invoke(app, ["init"])
    assert result.exit_code == 0

    config_text = Path("flow_props.toml").read_text()
    assert "[stations]" in config_text
    assert "[bl]" in config_text
    assert (
        "#--------------------------------------------------\n# input\n#--------------------------------------------------"
        in config_text
    )
    assert 'profiles_output = "bl_profiles.dat"' in config_text
    assert (
        "# Leave this table empty to process all i-stations (0 through Nx - 1, step 1)."
        in config_text
    )
    assert "# x_s = 0.05" in config_text
    assert "# To select fewer stations, uncomment exactly one mode below." in config_text
    assert "# Mode 2: select i-indices from i_s to i_e, inclusive, with step di." in config_text
    assert "# Mode 3: select only these i-indices." in config_text
    assert '# CFD solution file.\nfname = "base_flow.hdf5"' in config_text
    assert (
        '# For split file formats, uncomment and set the separate grid file.\n# gname = "grid.s8"'
        in config_text
    )
    assert '# Tecplot ASCII BL property table.\noutput = "bl_properties.dat"' in config_text
    assert "# [gas]" in config_text
    assert "generated by: flow-props init" in config_text


